"""Check bounded logging and exact continuation before long cluster runs."""

from contextlib import redirect_stdout
import io
from pathlib import Path
import tempfile
import subprocess
import unittest
from unittest.mock import patch

import jax
import numpy as np
import orbax.checkpoint as ocp

from rl.cluster_jobs import JOBS, job_config
from rl.cluster_train import restore_runner, stable_runner
from rl import cluster_train
from rl.train_policy import make_train, summarize_training_metrics


class ClusterTrainingTests(unittest.TestCase):
    def setUp(self):
        # Orbax 0.6.4's diagnostic logger can divide by a zero-duration Windows
        # clock tick for tiny test checkpoints. Serialization remains real.
        diagnostic = patch("orbax.checkpoint._src.handlers.base_pytree_checkpoint_handler._log_io_per_sec_metric")
        diagnostic.start()
        self.addCleanup(diagnostic.stop)

    def test_only_observation_and_experiment_name_differ_within_each_robot(self):
        for start in (0, 4):
            configs = [job_config(job.index) for job in JOBS[start:start + 4]]
            normalized = [{key: value for key, value in config.items()
                           if key not in ("EXP_NAME", "EQUIVARIANT")} for config in configs]
            self.assertTrue(all(config == normalized[0] for config in normalized))
            self.assertEqual(configs[0]["NUM_LAYERS"], 6)
            self.assertEqual(configs[0]["NUM_NODES"], 128)
        self.assertEqual(job_config(0)["TOTAL_TIMESTEPS"], 1_000_000_000)
        self.assertEqual(job_config(4)["TOTAL_TIMESTEPS"], 400_000_000)

    def test_editable_install_metadata_is_excluded_but_source_edits_are_detected(self):
        with tempfile.TemporaryDirectory() as temporary:
            root = Path(temporary)
            def git(*arguments):
                return subprocess.check_output(["git", *arguments], cwd=root, text=True, stderr=subprocess.STDOUT)
            git("init")
            metadata = root / "example.egg-info" / "SOURCES.txt"
            metadata.parent.mkdir()
            metadata.write_text("original build metadata")
            code = root / "source.py"
            code.write_text("value = 1\n")
            git("add", ".")
            git("-c", "user.name=Test", "-c", "user.email=test@example.invalid", "commit", "-m", "fixture")
            metadata.write_text("regenerated by pip install -e .")
            with patch.object(cluster_train, "REPO_ROOT", root):
                self.assertEqual(cluster_train.source_info()["dirty_files"], [])
                code.write_text("value = 2\n")
                self.assertTrue(any("source.py" in line for line in cluster_train.source_info()["dirty_files"]))

    def test_compact_metrics_and_resumed_chunks_preserve_training(self):
        config = job_config(3, smoke=True)
        config.update(TOTAL_TIMESTEPS=128, NUM_LAYERS=1, NUM_NODES=8)
        keys = jax.random.split(jax.random.PRNGKey(3), 1)
        with redirect_stdout(io.StringIO()):
            raw_fn = jax.jit(jax.vmap(make_train({**config, "COMPACT_METRICS": False})))
            raw = jax.block_until_ready(raw_fn(keys))
            compact_fn = jax.jit(jax.vmap(make_train(config.copy())))
            compact = jax.block_until_ready(compact_fn(keys))
            initialize = jax.jit(jax.vmap(make_train({**config, "INITIALIZE_ONLY": True})))
            template = stable_runner(jax.block_until_ready(initialize(keys))["runner_state"])
            chunk_fn = jax.jit(jax.vmap(make_train({**config, "UPDATES_PER_CALL": 2})))
            first = jax.block_until_ready(chunk_fn(keys, template))
        with tempfile.TemporaryDirectory() as temporary:
            checkpoint = Path(temporary) / "state"
            ocp.PyTreeCheckpointer().save(str(checkpoint), first["runner_state"])
            restored = restore_runner(checkpoint, template)
            second = jax.block_until_ready(chunk_fn(keys, restored))
        for expected, observed in zip(jax.tree_util.tree_leaves(raw["runner_state"]),
                                      jax.tree_util.tree_leaves(compact["runner_state"])):
            np.testing.assert_allclose(observed, expected, atol=1e-7, rtol=1e-6)
        for expected, observed in zip(jax.tree_util.tree_leaves(compact["runner_state"]),
                                      jax.tree_util.tree_leaves(second["runner_state"])):
            np.testing.assert_allclose(observed, expected, atol=1e-7, rtol=1e-6)
        summarized = jax.vmap(jax.vmap(summarize_training_metrics))(raw["metrics"])
        for name in summarized:
            np.testing.assert_allclose(compact["metrics"][name], summarized[name], atol=1e-5)
            joined = np.concatenate([first["metrics"][name], second["metrics"][name]], axis=1)
            np.testing.assert_allclose(compact["metrics"][name], joined, atol=1e-5)
        self.assertEqual(compact["metrics"]["return_mean"].shape, (1, 4))


if __name__ == "__main__":
    unittest.main()
